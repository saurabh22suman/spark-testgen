    def _generate_helper_functions(self) -> str:
        """Generate helper functions for test assertions."""
        return dedent('''\
            # =============================================================================
            # Helper Functions
            # =============================================================================


            def assert_schemas_equal(
                actual: StructType,
                expected: StructType,
                check_nullable: bool = True,
            ) -> None:
                """Assert two schemas are equal.

                Args:
                    actual: Actual schema
                    expected: Expected schema
                    check_nullable: Whether to check nullability
                """
                assert len(actual.fields) == len(expected.fields), (
                    f"Field count mismatch: {len(actual.fields)} vs {len(expected.fields)}"
                )

                for actual_field, expected_field in zip(actual.fields, expected.fields):
                    assert actual_field.name == expected_field.name, (
                        f"Field name mismatch: {actual_field.name} vs {expected_field.name}"
                    )
                    assert str(actual_field.dataType) == str(expected_field.dataType), (
                        f"Field type mismatch for {actual_field.name}: "
                        f"{actual_field.dataType} vs {expected_field.dataType}"
                    )
                    if check_nullable:
                        assert actual_field.nullable == expected_field.nullable, (
                            f"Nullability mismatch for {actual_field.name}: "
                            f"{actual_field.nullable} vs {expected_field.nullable}"
                        )


            def assert_dataframes_equal(
                actual: DataFrame,
                expected: DataFrame,
                check_order: bool = False,
            ) -> None:
                """Assert two DataFrames have equal content.

                Args:
                    actual: Actual DataFrame
                    expected: Expected DataFrame
                    check_order: Whether row order matters
                """
                # Check schemas match
                assert_schemas_equal(actual.schema, expected.schema)

                # Get data
                if check_order:
                    actual_rows = actual.collect()
                    expected_rows = expected.collect()
                else:
                    # Sort by all columns for comparison
                    sort_cols = [f.name for f in actual.schema.fields]
                    actual_rows = actual.orderBy(*sort_cols).collect()
                    expected_rows = expected.orderBy(*sort_cols).collect()

                assert len(actual_rows) == len(expected_rows), (
                    f"Row count mismatch: {len(actual_rows)} vs {len(expected_rows)}"
                )

                for i, (actual_row, expected_row) in enumerate(zip(actual_rows, expected_rows)):
                    assert actual_row == expected_row, (
                        f"Row {i} mismatch:\\n  Actual: {actual_row}\\n  Expected: {expected_row}"
                    )''')

