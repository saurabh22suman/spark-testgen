"""Test file generator for PySpark transformations."""

from __future__ import annotations

import logging
from pathlib import Path
from textwrap import dedent
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ..inference.schema import SchemaAnalysis, SchemaComparison

from .paths import TestPaths

logger = logging.getLogger(__name__)


class TestWriter:
    """Generates pytest test files for DataFrame transformations.

    Creates test files with:
    - Schema stability tests
    - Snapshot comparison tests
    - Null/edge case handling tests
    - Soft plan regression tests
    """

    def generate(
        self,
        function_name: str,
        _input_analysis: SchemaAnalysis,
        output_analysis: SchemaAnalysis,
        schema_comparison: SchemaComparison,
        paths: TestPaths,
    ) -> str:
        """Generate test file content.

        Args:
            function_name: Name of the function being tested
            _input_analysis: Analysis of input schema (unused, reserved for future)
            output_analysis: Analysis of output schema
            schema_comparison: Comparison between input/output schemas
            paths: TestPaths for resource locations

        Returns:
            Complete test file content as string
        """
        sections = [
            self._generate_header(function_name),
            self._generate_imports(),
            self._generate_constants(function_name, paths),
            self._generate_fixtures(function_name),
            self._generate_helper_functions(),
            self._generate_schema_tests(output_analysis, schema_comparison),
            self._generate_snapshot_tests(function_name),
            self._generate_null_handling_tests(function_name, output_analysis),
            self._generate_plan_tests(function_name),
        ]

        return "\n\n".join(sections)

    def write(self, content: str, path: Path) -> None:
        """Write test content to file.

        Args:
            content: Test file content
            path: Target file path
        """
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        logger.info(f"Generated test file: {path}")

    def _generate_header(self, function_name: str) -> str:
        """Generate file header with docstring."""
        return dedent(f'''\
            """
            Auto-generated tests for `{function_name}`.

            Generated by spark-testgen. These tests verify:
            - Schema stability
            - Output snapshot matching
            - Null value handling
            - Execution plan stability (soft check)

            To use these tests:
            1. Import your transformation function
            2. Uncomment the function call lines
            3. Run: pytest {Path("tests") / f"test_{function_name}.py"}

            After verifying tests pass, you can customize them as needed.
            """''')

